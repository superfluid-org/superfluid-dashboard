/**
 * Regenerates src/features/clearMacro/dashboardClearMacroAbi.generated.ts from the
 * Foundry build artifact of contracts/src/DashboardClearMacro.sol.
 *
 * Usage:
 *   pnpm contracts:abi          (forge build + this script)
 *   node scripts/generate-clear-macro-abi.mjs   (reuse an existing artifact)
 *
 * The output module must stay loadable under Node's native type stripping
 * (scripts/clearmacro-relay-replay.mjs imports it), so it contains nothing but a
 * const-asserted array literal.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = path.join(
  repoRoot,
  "contracts/out/DashboardClearMacro.sol/DashboardClearMacro.json"
);
const outputPath = path.join(
  repoRoot,
  "src/features/clearMacro/dashboardClearMacroAbi.generated.ts"
);

let artifact;
try {
  artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
} catch (error) {
  if (error.code === "ENOENT") {
    console.error(
      `Artifact not found: ${path.relative(repoRoot, artifactPath)}\n` +
        "Run `pnpm contracts:build` first (or use `pnpm contracts:abi` to do both)."
    );
    process.exit(1);
  }
  throw error;
}

const { abi } = artifact;
if (!Array.isArray(abi) || abi.length === 0) {
  console.error(`Artifact at ${path.relative(repoRoot, artifactPath)} has no ABI.`);
  process.exit(1);
}

const output = `// AUTO-GENERATED by scripts/generate-clear-macro-abi.mjs — do not edit.
// Source: contracts/src/DashboardClearMacro.sol via the Foundry artifact
// contracts/out/DashboardClearMacro.sol/DashboardClearMacro.json.
// Regenerate with: pnpm contracts:abi

export const dashboardClearMacroAbi = ${JSON.stringify(abi, null, 2)} as const;
`;

writeFileSync(outputPath, output);
console.log(
  `Wrote ${path.relative(repoRoot, outputPath)} (${abi.length} ABI entries).`
);
